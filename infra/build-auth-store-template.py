#!/usr/bin/env python3
"""Refresh CloudFormation's inline handler from its canonical source, without dependencies."""

from pathlib import Path
import hashlib

root = Path(__file__).resolve().parent
template_path = root / "auth-store.yaml"
source = (root / "auth-store-handler.cjs").read_text()
start = "          // BEGIN INLINE HANDLER -- generated by build-auth-store-template.py\n"
end = "          // END INLINE HANDLER\n"
template = template_path.read_text()
before, remainder = template.split(start, 1)
_, after = remainder.split(end, 1)
digest = hashlib.sha256(source.encode()).hexdigest()
embedded = f"          // Source SHA-256: {digest}\n"
embedded += "".join(("          " + line if line else "") + "\n" for line in source.splitlines())
template_path.write_text(before + start + embedded + end + after)
print(f"Embedded auth-store-handler.cjs ({len(source.encode())} bytes).")
